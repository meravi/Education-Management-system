CREATE TABLE IF NOT EXISTS `sub_class_name` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `subject` VARCHAR(100) NOT NULL,
  `class` VARCHAR(50) NOT NULL,
  PRIMARY KEY (`id`)
